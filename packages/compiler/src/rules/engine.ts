import { compile } from '../compile';
import type { CompileResult, Graph } from '../types';
import type { Finding, FixPatch, Rule, RuleContext } from './types';

export function makeContext(graph: Graph, result: CompileResult): RuleContext {
  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  const edgesOut = (id: string) => graph.edges.filter((e) => e.source === id).map((e) => byId.get(e.target)!).filter(Boolean);
  const edgesIn = (id: string) => graph.edges.filter((e) => e.target === id).map((e) => byId.get(e.source)!).filter(Boolean);
  return {
    graph,
    result,
    node: (id) => byId.get(id),
    ofType: (t) => graph.nodes.filter((n) => n.type === t),
    inputs: (id) => {
      // judge what the code really says: drop inputs the compiler added that an imported source did not have
      const eff = { ...(result.modules[id]?.effective ?? {}) };
      for (const k of byId.get(id)?.notInSource ?? []) delete eff[k];
      return eff;
    },
    out: (id, t) => edgesOut(id).filter((n) => !t || n.type === t),
    into: (id, t) => edgesIn(id).filter((n) => !t || n.type === t),
    services: (id) => {
      const s = (result.modules[id]?.effective ?? {}).services; // imported services are kept whole, so this is the source's own
      return s && typeof s === 'object' ? (s as Record<string, any>) : {};
    },
    tierOf: (id) => {
      const p = byId.get(byId.get(id)?.parentId ?? '');
      return p?.type === 'aws.subnet' ? String(p.properties.tier) : undefined;
    },
  };
}

const order = { high: 0, medium: 1, low: 2 } as const;

const applyPatch = (g: Graph, p: FixPatch): Graph => ({ ...g, nodes: g.nodes.map((n) => (n.id === p.nodeId ? { ...n, properties: { ...n.properties, ...p.set } } : n)) });

/**
 * Run rules over a compiled architecture. Pure and deterministic: the same input always gives the same findings.
 * A one-click fix is only kept when applying it really clears the finding (settings kept from imported Terraform
 * can override a form change, and a fix that silently does nothing is worse than none).
 */
export function runRules(graph: Graph, result: CompileResult, rules: Rule[], opts: { verifyFixes?: boolean } = {}): Finding[] {
  const ctx = makeContext(graph, result);
  const out: Finding[] = [];
  for (const r of rules) {
    let found: ReturnType<Rule['check']> = [];
    try { found = r.check(ctx); } catch { continue; } // one broken rule must never hide the others
    for (const f of found) out.push({ rule: r.id, title: r.title, severity: r.severity, ...f });
  }
  if (opts.verifyFixes !== false) {
    for (const f of out) {
      if (!f.fix) continue;
      if (!Object.keys(f.fix.set).length) { delete f.fix; continue; }
      const g2 = applyPatch(graph, f.fix);
      let still = true;
      try {
        const rule = rules.find((r) => r.id === f.rule)!;
        still = rule.check(makeContext(g2, compile(g2, { lenient: true }))).some((x) => x.nodeId === f.nodeId);
      } catch { /* if we cannot prove the fix works, do not offer it */ }
      if (still) delete f.fix;
    }
  }
  return out.sort((a, b) => order[a.severity] - order[b.severity] || a.rule.localeCompare(b.rule) || a.nodeId.localeCompare(b.nodeId));
}

/** A prompt a person can paste into Claude Code to fix a finding. Built from facts, never generated by a model. */
export function findingPrompt(f: Finding, ctx: { nodeName: string; nodeLabel: string; folder?: string; repo?: string }): string {
  const where = ctx.folder ? ` in the Terraform under \`${ctx.folder}\`` : '';
  return [
    `Fix this compliance finding${where}${ctx.repo ? ` (repo ${ctx.repo})` : ''}.`,
    '',
    `Control: ${f.rule} — ${f.title}`,
    `Resource: ${ctx.nodeLabel} "${ctx.nodeName}"`,
    `Problem: ${f.message}`,
    `Required change: ${f.suggestion}`,
    ...(f.terraform ? ['', 'Terraform detail:', f.terraform] : []),
    '',
    'Constraints: keep using the existing approved modules, change only what is needed, run `terraform fmt` and `terraform validate`, and show me the diff before applying.',
  ].join('\n');
}

export const bySeverity = (fs: Finding[]) => ({ high: fs.filter((f) => f.severity === 'high').length, medium: fs.filter((f) => f.severity === 'medium').length, low: fs.filter((f) => f.severity === 'low').length });
