import { CATALOG, Ctx, Resolved, snake } from './catalog';
import { printBlock, printModule, quote, raw } from './hcl';
import { pipelineYaml } from './pipeline';
import { validateGraph } from './validate';
import type { BlockRange, CompileResult, CompiledFile, Diagnostic, Graph } from './types';

export const GENERATOR = 'cloud-canvas@0.1.0';
const TYPE_ORDER = ['aws.vpc', 'aws.acm', 'aws.s3', 'aws.dynamodb', 'aws.sqs', 'aws.sns', 'aws.rds_postgres', 'aws.ecs_fargate', 'aws.lambda', 'aws.alb', 'aws.apigw', 'aws.cloudfront'];

export function compile(g: Graph): CompileResult {
  const diagnostics: Diagnostic[] = validateGraph(g);
  const hasError = () => diagnostics.some((d) => d.severity === 'error');

  // ── resolve nodes → labelled resources (deterministic, collision-safe)
  const used = new Set<string>();
  const resolved = new Map<string, Resolved>();
  const sorted = [...g.nodes]
    .filter((n) => CATALOG[n.type])
    .sort((a, b) => TYPE_ORDER.indexOf(a.type) - TYPE_ORDER.indexOf(b.type) || String(a.properties.name).localeCompare(String(b.properties.name)) || a.id.localeCompare(b.id));
  for (const node of sorted) {
    const def = CATALOG[node.type];
    let label = snake(String(node.properties.name || node.id));
    for (let i = 2; used.has(label) || used.has(`${label}_sg`); i++) label = `${snake(String(node.properties.name))}_${i}`;
    used.add(label);
    resolved.set(node.id, { node, label, def, p: node.properties });
  }

  const edges = g.edges.filter((e) => resolved.has(e.source) && resolved.has(e.target));
  const blocks: string[] = [];
  const ranges: BlockRange[] = [];
  const header: string[] = [
    `# Generated by ${GENERATOR}. Do not edit by hand; changes are overwritten.`,
    '',
  ];
  let line = header.length;

  const sections: { nodeId: string; text: string }[] = [];

  if (!hasError()) {
    for (const r of resolved.values()) {
      const vpcNode = r.node.parentId ? resolved.get(r.node.parentId) : r.def.type === 'aws.vpc' ? r : undefined;
      const ctx: Ctx = {
        self: r,
        project: g.project,
        vpc: vpcNode,
        incoming: (t) => edges.filter((e) => e.target === r.node.id).map((e) => resolved.get(e.source)!).filter((x) => x.node.type === t).sort(byLabel),
        outgoing: (t) => edges.filter((e) => e.source === r.node.id).map((e) => resolved.get(e.target)!).filter((x) => x.node.type === t).sort(byLabel),
        ref: (x, attr) => raw(`module.${x.label}.${attr}`),
        warn: (message) => diagnostics.push({ severity: 'warning', nodeId: r.node.id, message }),
      };
      const res = r.def.build(ctx);
      const parts: string[] = [
        `# canvas:node id=${r.node.id} type=${r.node.type}\n` +
          printModule({ name: r.label, source: r.def.module.source, version: r.def.module.version, inputs: res.inputs }),
      ];
      for (const x of res.extraModules ?? []) parts.push(printModule({ name: x.label, source: x.source, version: x.version, inputs: x.inputs }));
      for (const rb of res.rawBlocks ?? []) parts.push(rb);
      sections.push({ nodeId: r.node.id, text: parts.join('\n\n') });
    }
    for (const s of sections) {
      const lines = s.text.split('\n').length;
      ranges.push({ nodeId: s.nodeId, file: 'main.tf', startLine: line + 1, endLine: line + lines });
      blocks.push(s.text);
      line += lines + 1;
    }
  }

  const needsAz = [...resolved.values()].some((r) => r.node.type === 'aws.vpc');
  const mainParts = [...header.slice(0, 1), ''];
  const mainHeadLines = mainParts.length;
  // recompute ranges relative to the actual head
  const shift = mainHeadLines - header.length;
  const mainTf = hasError()
    ? `${header[0]}\n\n# Fix the errors on the canvas to generate Terraform.\n`
    : mainParts.join('\n') + '\n' + blocks.join('\n\n') + '\n';
  if (!hasError()) for (const r of ranges) { r.startLine += shift; r.endLine += shift; }

  const tagEntries: [string, string][] = [
    ['Project', g.project.name],
    ['Environment', g.project.environment],
    ['ManagedBy', 'cloud-canvas'],
    ...(g.project.squad ? [['Squad', g.project.squad] as [string, string]] : []),
  ];
  const w = Math.max(...tagEntries.map(([k]) => k.length));
  const tags = `locals {\n  mandatory_tags = {\n${tagEntries.map(([k, v]) => `    ${k.padEnd(w)} = ${quote(v)}`).join('\n')}\n  }\n}`;
  const provider = `provider "aws" {\n  region = ${quote(g.project.region)}\n\n  default_tags {\n    tags = local.mandatory_tags\n  }\n}`;
  const tfBlock = `terraform {\n  required_version = ">= 1.6.0"\n\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 5.70"\n    }\n  }\n}`;
  const az = needsAz ? '\n\n' + printBlock('data', ['aws_availability_zones', 'available'], { state: 'available' }) : '';
  const versionsTf = `${header[0]}\n\n${tfBlock}\n\n${provider}\n\n${tags}${az}\n`;

  const files: CompiledFile[] = [
    { path: 'main.tf', language: 'hcl', content: mainTf },
    { path: 'versions.tf', language: 'hcl', content: versionsTf },
    { path: 'azure-pipelines.yml', language: 'yaml', content: pipelineYaml(g) },
  ];
  return { files, blocks: ranges, diagnostics, ok: !hasError() };
}

const byLabel = (a: Resolved, b: Resolved) => a.label.localeCompare(b.label);
