import type { Graph } from './types';

export function pipelineYaml(g: Graph): string {
  const dir = `infra/${g.project.environment}`;
  return `# Generated by cloud-canvas@0.1.0. Do not edit by hand.
trigger:
  branches:
    include: [main]
  paths:
    include: [${dir}/*]

pool:
  name: self-hosted-linux

variables:
  workingDirectory: ${dir}
  environment: ${g.project.name}-${g.project.environment}

stages:
  - stage: validate
    jobs:
      - job: terraform_validate
        steps:
          - script: terraform init -backend=false && terraform fmt -check -recursive && terraform validate
            workingDirectory: $(workingDirectory)
            displayName: Terraform validate
  - stage: plan
    dependsOn: validate
    jobs:
      - job: terraform_plan
        steps:
          - script: terraform init && terraform plan -out=tfplan
            workingDirectory: $(workingDirectory)
            displayName: Terraform plan
  - stage: apply
    dependsOn: plan
    condition: and(succeeded(), eq(variables['Build.SourceBranch'], 'refs/heads/main'))
    jobs:
      - deployment: terraform_apply
        environment: $(environment)
        strategy:
          runOnce:
            deploy:
              steps:
                - script: terraform init && terraform apply -auto-approve tfplan
                  workingDirectory: $(workingDirectory)
                  displayName: Terraform apply
`;
}
